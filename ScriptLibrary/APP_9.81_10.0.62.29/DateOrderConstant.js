var MMDDYY = 1;
var DDMMYY = 2;
var YYMMDD = 3;
var MMDDYYYY = 4;
var DDMMYYYY = 5;
var YYYYMMDD = 6;
function mmddyy()
{
   return MMDDYY;
}

function ddmmyy()
{
   	return DDMMYY;
}
function yymmdd()
{
   	return YYMMDD;
}
function mmddyyyy()
{
   	return MMDDYYYY;
}
function ddmmyyyy()
{
   	return DDMMYYYY;
}
function yyyymmdd()
{
	return YYYYMMDD;
}

